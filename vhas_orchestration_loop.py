
from vhas_threshold_governor import VHASThresholdGovernor
from vhas_self_correction import VHASSyntaxCorrectionCore
from vhas_git_governor import VHASGitGovernor
from vhas_autonomous_policy import VHASAutonomousPolicy


class VHASAutomatedEngine:
    def __init__(self, repo_dir="."):
        self.repo_dir = repo_dir
        self.governor = VHASThresholdGovernor()
        self.correction_core = VHASSyntaxCorrectionCore(repo_dir)
        self.git_governor = VHASGitGovernor(repo_dir)
        self.autonomous_policy = VHASAutonomousPolicy()

    def run_evolution_cycle(self, h, a, c):
        errors = []
        review_candidates = []

        def result():
            if errors:
                status = "review_required"
            elif review_candidates:
                status = "manual_review_pending"
            else:
                status = "completed_no_candidates"

            return {
                "mode": "recommendation_only",
                "applied_changes": 0,
                "remote_push_performed": False,
                "status": status,
                "errors": list(errors),
                "review_candidates": list(review_candidates),
            }

        try:
            required_actions = self.governor.audit_system_state(h, a, c)
        except Exception as exc:
            errors.append({
                "action_index": None,
                "reason": f"Governor audit failed: {type(exc).__name__}",
            })
            return result()

        if not isinstance(required_actions, (list, tuple)):
            errors.append({
                "action_index": None,
                "reason": "Invalid action collection",
            })
            return result()

        if not required_actions:
            return result()

        simulated_code_patch = (
            "// Production patch generated by VHAS 9.0 Core\n"
            "pub fn optimized_compute_node() -> f64 {\n"
            "    let volatile_bounds = vec![1.0, 2.0];\n"
            "    volatile_bounds\n"
            "}"
        )

        for index, action in enumerate(required_actions):
            if not isinstance(action, dict):
                errors.append({
                    "action_index": index,
                    "reason": "Malformed action",
                })
                continue

            target_file = action.get("target")

            if not isinstance(target_file, str) or not target_file.strip():
                errors.append({
                    "action_index": index,
                    "reason": "Missing or invalid action target",
                })
                continue

            try:
                policy_result = self.autonomous_policy.evaluate(
                    target_file, simulated_code_patch
                )
            except Exception as exc:
                errors.append({
                    "action_index": index,
                    "reason": f"Policy evaluation failed: {type(exc).__name__}",
                })
                continue

            if not isinstance(policy_result, dict):
                errors.append({
                    "action_index": index,
                    "reason": "Invalid policy response",
                })
                continue

            if (
                policy_result.get("approved") is not False
                or type(policy_result.get("eligible_for_review")) is not bool
            ):
                errors.append({
                    "action_index": index,
                    "reason": "Incomplete or unsafe policy decision",
                })
                continue

            if not policy_result["eligible_for_review"]:
                continue

            try:
                validated = self.correction_core.run_pipeline_validation(
                    target_file, simulated_code_patch
                )
            except Exception as exc:
                errors.append({
                    "action_index": index,
                    "reason": f"Validation failed: {type(exc).__name__}",
                })
                continue

            if validated is True:
                review_candidates.append({
                    "action_index": index,
                    "target": target_file,
                    "status": "awaiting_manual_review",
                })
            elif validated is not False:
                errors.append({
                    "action_index": index,
                    "reason": "Invalid validation response",
                })

        return result()


if __name__ == "__main__":
    engine = VHASAutomatedEngine("./")
    engine.run_evolution_cycle(1.0, 1.0, 0.89)
